"""M1 Stage A — ``parse_ddl_files`` (sqlglot DDL parse with per-file fallback).

Walks ``--ddl-path`` (file or directory) and runs ``sqlglot.parse`` on
every ``*.sql`` file. The output is a flat list of parsed top-level
``sqlglot.Expression`` nodes (one per ``CREATE`` statement encountered)
plus a parallel list of :class:`ParseError` records describing every
file that failed to parse cleanly.

Critical design (issue #189, mirroring M2 stage A — issue #205): a
single broken DDL file must not abort the whole run. The pipeline
falls back to logging a warning, recording a :class:`ParseError`, and
continuing — partial coverage of a legacy schema beats no coverage.

The parser does *not* attempt to tag individual unparseable statements
as ``parse_status="unparseable"`` the way M2's :mod:`sp_parser` does.
DDL files are typically generated by tooling (``expdp``, ``ssms``,
``db2look``) and either parse end-to-end or fail as a unit. Per-
statement fallback is M2's burden because real legacy SPs have hand-
written vendor-pragma bodies; M1's input is dump output.

Design spec §M1 Stage A (`docs/superpowers/specs/2026-05-22-data-modernization-design.md`).
"""

from __future__ import annotations

import logging
from dataclasses import dataclass
from typing import TYPE_CHECKING, cast

import sqlglot
from sqlglot import exp
from sqlglot.errors import ParseError as SqlglotParseError
from sqlglot.errors import SqlglotError

from primitives._shared.sql_files import walk_sql_files as _walk_sql_files

if TYPE_CHECKING:
    from pathlib import Path

logger = logging.getLogger(__name__)


# ---------------------------------------------------------------------------
# Dialect mapping
# ---------------------------------------------------------------------------

# Public dialect strings the M1 CLI accepts mapped to sqlglot dialect
# names. ``None`` selects sqlglot's ANSI parser, which we use for DB2
# because sqlglot 30.x ships no dedicated DB2 dialect. The mapping
# matches :mod:`primitives.stored_proc_analyze.shared.sp_parser` and
# the M-tier smoke test (``tests/test_db_dumps_parse.py``) so the
# fixture loop stays in lockstep.
_DIALECT_TO_SQLGLOT: dict[str, str | None] = {
    "oracle": "oracle",
    "tsql": "tsql",
    "mssql": "tsql",  # alias — sqlglot uses "tsql"
    "db2": None,
    "postgres": "postgres",
    "mysql": "mysql",
}

# Dialects the auto-detector tries, in order of preference. Oracle and
# T-SQL come first because the bundled fixtures exercise their specific
# grammars; ANSI/None is the universal fallback. PostgreSQL and MySQL
# are tried last because they are forward-compatible with most ANSI
# DDL and would mis-claim oracle/tsql input otherwise.
_AUTO_DIALECTS: tuple[str, ...] = ("oracle", "tsql", "db2", "postgres", "mysql")


# ---------------------------------------------------------------------------
# ParseError — per-file failure record
# ---------------------------------------------------------------------------


@dataclass(frozen=True)
class ParseError:
    """A single per-file DDL parse failure.

    Returned as the second element of :func:`parse_ddl_files`. The
    orchestrator (M1-11) folds these into ``SchemaDigest`` provenance
    + stderr so consumers can see *which* files were skipped without
    having to re-run the parser.

    ``line`` and ``column`` are best-effort: sqlglot's
    :class:`~sqlglot.errors.ParseError` carries a list of error dicts
    with ``line`` / ``col`` keys when the failure is a true grammar
    miss. They fall back to ``None`` when the error is structural
    (e.g. file read error, sqlglot returned ``None`` on a non-empty
    input).
    """

    path: Path
    message: str
    line: int | None = None
    column: int | None = None


# ---------------------------------------------------------------------------
# Public entry point
# ---------------------------------------------------------------------------


def parse_ddl_files(
    ddl_path: Path,
    dialect: str = "auto",
) -> tuple[list[exp.Expression], list[ParseError]]:
    """Walk ``ddl_path`` and parse every ``*.sql`` file with sqlglot.

    Args:
        ddl_path: A file (``.sql``) or a directory walked recursively for
            ``.sql`` files. Symlinks are not followed (matches M2's
            ``sp_parser`` semantics — see SPEC.md "File contract").
        dialect: ``"auto"`` (default), ``"oracle"``, ``"tsql"`` /
            ``"mssql"``, ``"db2"``, ``"postgres"``, or ``"mysql"``.
            ``"auto"`` runs each file through every dialect in
            :data:`_AUTO_DIALECTS` order and picks the first one whose
            parse succeeds without raising.

    Returns:
        A two-tuple of ``(expressions, errors)``:

        * ``expressions`` — flat list of top-level :class:`exp.Expression`
          nodes (one per ``CREATE`` / ``ALTER`` statement) across every
          successfully-parsed file. Order matches file walk + textual
          order within each file. ``None`` entries that sqlglot can
          emit for trailing semicolons are filtered out so downstream
          Stage B can iterate without a ``None``-guard.
        * ``errors`` — one :class:`ParseError` per file that failed to
          parse. An empty input directory yields ``([], [])``.

    Raises:
        FileNotFoundError: If ``ddl_path`` does not exist.
        ValueError: If ``dialect`` is not one of the supported strings.
    """
    if not ddl_path.exists():
        raise FileNotFoundError(f"--ddl-path not found: {ddl_path}")

    if dialect != "auto" and dialect not in _DIALECT_TO_SQLGLOT:
        raise ValueError(
            f"unsupported dialect {dialect!r}; "
            f"expected one of: auto, {', '.join(sorted(_DIALECT_TO_SQLGLOT))}"
        )

    expressions: list[exp.Expression] = []
    errors: list[ParseError] = []
    for sql_file in _walk_sql_files(ddl_path):
        file_exprs, file_error = _parse_one_file(sql_file, dialect)
        expressions.extend(file_exprs)
        if file_error is not None:
            errors.append(file_error)
    return expressions, errors


# ---------------------------------------------------------------------------
# Per-file parsing
# ---------------------------------------------------------------------------


def _parse_one_file(
    sql_file: Path,
    dialect: str,
) -> tuple[list[exp.Expression], ParseError | None]:
    """Parse a single ``.sql`` file, returning ``(expressions, error_or_None)``.

    A successful parse yields a non-empty error of ``None``. A failed
    parse yields an empty expressions list and a populated
    :class:`ParseError`. File I/O errors are caught and routed through
    the same error channel so the caller never sees a raised exception.

    In ``dialect="auto"`` mode, ``_detect_dialect`` returns both the
    winning dialect string and the already-parsed result so the winner
    parse is reused here rather than re-parsed (issue #814).
    """
    try:
        text = sql_file.read_text(encoding="utf-8")
    except OSError as exc:  # pragma: no cover — defended against, hard to trigger
        logger.warning("could not read %s: %s", sql_file, exc)
        return [], ParseError(path=sql_file, message=f"read error: {exc}")

    if dialect == "auto":
        effective_dialect, cached_parsed = _detect_dialect(text)
    else:
        effective_dialect = dialect
        cached_parsed = None

    if cached_parsed is not None:
        # Reuse the parse result from auto-detection — no second parse needed.
        parsed: list[exp.Expression | None] = cached_parsed
    else:
        sqlglot_dialect = _DIALECT_TO_SQLGLOT.get(effective_dialect)
        try:
            # Cast: same Expr-alias alignment as in ``_detect_dialect`` below.
            parsed = cast(
                "list[exp.Expression | None]",
                sqlglot.parse(text, dialect=sqlglot_dialect),
            )
        except SqlglotParseError as exc:
            logger.warning("sqlglot ParseError on %s: %s", sql_file, exc)
            return [], _build_parse_error(sql_file, exc)
        except SqlglotError as exc:  # pragma: no cover — caught for safety
            logger.warning("sqlglot error on %s: %s", sql_file, exc)
            return [], ParseError(path=sql_file, message=str(exc))

    # ``sqlglot.parse`` may return ``[None]`` for a trailing semicolon or
    # an empty input — filter those out so downstream stages can iterate
    # the expression list without a ``None``-guard. A file that yields
    # only ``None`` entries is treated as empty (no error, no expressions).
    # sqlglot 30.x types the return as ``list[Expr | None]`` where ``Expr``
    # is an alias of :class:`exp.Expression` declared in
    # ``sqlglot/_typing.py``; mypy doesn't follow the alias at the
    # comprehension boundary, so we cast explicitly. Runtime is a no-op.
    real_exprs = cast("list[exp.Expression]", [e for e in parsed if e is not None])
    return real_exprs, None


def _build_parse_error(sql_file: Path, exc: SqlglotParseError) -> ParseError:
    """Build a :class:`ParseError` from a sqlglot exception.

    sqlglot's :class:`~sqlglot.errors.ParseError` carries an ``errors``
    list of ``{description, line, col, ...}`` dicts when the failure is
    a true grammar miss. We surface the first entry's coordinates so the
    consumer's stderr log says *which line* of the dump broke — a
    one-line vs whole-file-bad distinction the M-tier triage prompt
    in M1-9 relies on.
    """
    line: int | None = None
    column: int | None = None
    raw_errors = getattr(exc, "errors", None)
    if raw_errors:
        first = raw_errors[0]
        if isinstance(first, dict):
            raw_line = first.get("line")
            raw_col = first.get("col")
            if isinstance(raw_line, int):
                line = raw_line
            if isinstance(raw_col, int):
                column = raw_col
    return ParseError(path=sql_file, message=str(exc), line=line, column=column)


# ---------------------------------------------------------------------------
# Auto-detection
# ---------------------------------------------------------------------------


def _detect_dialect(
    text: str,
) -> tuple[str, list[exp.Expression | None] | None]:
    """Return ``(dialect, parsed)`` for the first candidate that parses ``text``.

    "Parses" = ``sqlglot.parse`` does not raise. The returned ``parsed``
    list is the already-computed result of the winning call so the caller
    can reuse it without a second parse — eliminating the redundant 6th
    parse in the ``dialect="auto"`` path (issue #814).

    Empty input falls back to ``("db2", None)`` — ``None`` for ``parsed``
    signals "not parsed yet" and lets the caller invoke ``sqlglot.parse``
    itself (which will return an empty list, not raise). The order in
    :data:`_AUTO_DIALECTS` encodes the preference: Oracle, then T-SQL,
    then ANSI (DB2), then PostgreSQL / MySQL — the M-tier fixtures cover
    the first three so they win the tie when a sample is ambiguous.

    The detector deliberately does not score by "best parse" because
    a permissive ANSI parser will succeed on most inputs and would
    drown the dialect signal. First-match-wins keeps the priority
    explicit.
    """
    if not text.strip():
        return "db2", None

    for candidate in _AUTO_DIALECTS:
        sqlglot_dialect = _DIALECT_TO_SQLGLOT.get(candidate)
        try:
            # Cast aligns sqlglot's internal ``Expr`` alias with the public
            # ``exp.Expression`` type that mypy can track (same pattern as the
            # existing cast in ``_parse_one_file``). Runtime is a no-op.
            parsed = cast(
                "list[exp.Expression | None]",
                sqlglot.parse(text, dialect=sqlglot_dialect),
            )
        except (SqlglotParseError, SqlglotError):
            continue
        return candidate, parsed
    # Pathological fallback: every dialect rejected the text. The caller
    # will see the same rejection itself and route through the per-file
    # error path; we return the universal default so the caller's
    # branch is consistent.
    return "db2", None


__all__ = ["ParseError", "parse_ddl_files"]
